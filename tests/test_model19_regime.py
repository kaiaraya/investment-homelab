def test_transition_tightening_snapshot_sweep(engine, zones, forensics):
    """Whole-snapshot census: the gate must hold on every frozen row."""
    rules = {"DEFENSIVE": {}, "TRANSITION": {}, "AGGRESSIVE_LONG": {}, "AGGRESSIVE_SHORT": {}}
    tightened_on_transition = 0
    flag_true_on_transition = 0
    flag_true_off_transition = 0
    leaked = []
    total = 0
    for date in engine.dates():
        if date not in zones:
            continue
        total += 1
        zone = zones[date]
        day = engine.day(date)
        fore = forensics.get(date)
        cross = getattr(fore, "sqn_crosses_10d", 0.0) or 0.0
        peak = getattr(fore, "running_peak_delta", 0.0) or 0.0

        result = re.transition_tightening_for_day(day, zone.zone_mode, cross, peak)
        bucket = rules.setdefault(zone.zone_mode, {})
        bucket[result.rule] = bucket.get(result.rule, 0) + 1

        if zone.zone_mode == "TRANSITION":
            tightened_on_transition += bool(result.apply)
            flag_true_on_transition += bool(result.is_trans_tight_day)
        elif result.is_trans_tight_day:
            flag_true_off_transition += 1

        if not day.use_trans_tight and (result.apply or result.zero_short or result.zero_long):
            leaked.append(date)
        if result.apply and not result.is_trans_tight_day:
            leaked.append(date)

    assert total == 901
    assert rules["TRANSITION"] == {
        "none": 344,
        "thrust_exhaustion": 45,
        "sqn_whipsaw": 3,
        "neutral_volatile": 3,
    }
    assert sum(rules["TRANSITION"].values()) == 395
    assert rules["DEFENSIVE"].get("neutral_volatile") == 2
    assert rules["AGGRESSIVE_LONG"].get("neutral_volatile") == 7
    assert rules["AGGRESSIVE_SHORT"].get("neutral_volatile") == 3
    # 88 of the 395 TRANSITION days carry a transition-tight tactic; the other
    # 307 (and the 236 with loud triggers) must stay at the reference default.
    assert tightened_on_transition == 51
    assert flag_true_on_transition == 51
    assert flag_true_off_transition == 12          # Neutral Volatile outside TRANSITION
    assert leaked == []


