def test_vendor_csv_run_length_agrees_except_after_the_data_gap(forensics, thrust):
    """846/901 exact; the 55 exceptions are all at/after the 2026-05-01..04 gap."""
    matches = 0
    mismatches: List[Tuple[str, int, Optional[int]]] = []
    for date_str, row in forensics.items():
        point = thrust.get(date_str)
        if point is None or row.running_wave_dur is None:
            continue
        if point.days_in_wave == row.running_wave_dur:
            matches += 1
        else:
            mismatches.append((date_str, point.days_in_wave, row.running_wave_dur))
    assert len(mismatches) == VENDOR_DUR_MISMATCH_COUNT
    assert matches == 846
    assert all(date >= VENDOR_GAP_DATE for date, _, _ in mismatches), (
        "every run-length discrepancy must sit at/after the documented snapshot gap"
    )
    # The vendor engine ran on a longer series: rows dropped from the frozen CSV
    # (2026-05-01..04 etc.) still advance its ``running_wave_dur``, so the offset
    # only moves in the vendor's favour. The single exception is the final day,
    # whose delta the vendor revised (-82 vs -115 in the zone file).
    for date_str, mine, vendor in mismatches:
        if date_str == "2026-10-08":
            assert vendor == mine - 1
        else:
            assert vendor >= mine


def test_vendor_csv_running_peak_matches_our_run_peaks(forensics, thrust):
    """Signed peak of |delta| inside the current run — an independent run check."""
    compared = 0
    mismatches = []
    for date_str, row in forensics.items():
        point = thrust.get(date_str)
        if point is None or row.running_peak_delta is None or date_str >= VENDOR_GAP_DATE:
            continue
        expected = point.sign * max(
            abs(other.delta)
            for other in thrust.values()
            if other.date <= date_str and other.sign == point.sign
            and other.date >= _run_start_date(thrust, date_str)
        )
        compared += 1
        if abs(expected - row.running_peak_delta) > 1e-9:
            mismatches.append((date_str, expected, row.running_peak_delta))
    assert compared == sum(
        1 for date_str in forensics if date_str < VENDOR_GAP_DATE
    )
    assert mismatches == []


def _run_start_date(thrust: Dict[str, wt.WaveThrustPoint], date_str: str) -> str:
    point = thrust[date_str]
    start = date_str
    for other in sorted(thrust.values(), key=lambda item: item.date, reverse=True):
        if other.date > date_str:
            continue
        if other.sign != point.sign:
            break
        start = other.date
    return start


