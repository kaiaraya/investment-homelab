def _notebook_label(sqn_v: float, vol_v: float, baseline: float) -> str:
    """Notebook CELL 5 lines 334-340, transliterated verbatim."""
    v_str = "Volatile" if vol_v > baseline else "Quiet"
    if sqn_v > 1.47:
        dir_name = "Very Bullish"
    elif sqn_v >= 0.75:
        dir_name = "Bullish"
    elif sqn_v >= 0.00:
        dir_name = "Neutral"
    elif sqn_v >= -0.70:
        dir_name = "Bearish"
    else:
        dir_name = "Very Bearish"
    return f"{dir_name} {v_str}"


def test_reference_parity_every_snapshot_row(engine):
    """1199 rows: port label == notebook formula, recomputed independently here."""
    series = engine.series
    mismatches = []
    for date_str in series.dates:
        expected = _notebook_label(series.sqn[date_str], series.vol_100d[date_str], series.baseline_vol)
        actual = engine.label(date_str)
        if expected != actual:
            mismatches.append((date_str, expected, actual))
    assert mismatches == []
    assert len(series.dates) == 1199


