def _write_sqn_json(tmp_path: Path, records: List[dict], baseline: Optional[float] = 0.855) -> Path:
    payload: Dict[str, object] = {"records": records}
    if baseline is not None:
        payload["historical_avg_volatility_pct"] = baseline
    path = tmp_path / "sqn.json"
    path.write_text(json.dumps(payload), encoding="utf-8")
    return path


def test_load_series_sorts_by_date(tmp_path):
    path = _write_sqn_json(
        tmp_path,
        [
            {"date": "2024-01-03", "sqn": 2.0, "volatility_100d": 0.9},
            {"date": "2024-01-02", "sqn": 1.0, "volatility_100d": 0.8},
        ],
    )
    series = re.load_regime_series(str(path))
    assert series.dates == ("2024-01-02", "2024-01-03")
    assert series.source_path == str(path)


