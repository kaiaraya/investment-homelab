    offenders = [
        name
        for name in _imported_modules(module_path)
        if any(name == root or name.startswith(root + ".") for root in FORBIDDEN_IMPORT_ROOTS)
    ]
    assert offenders == [], f"{module_path.name} imports forbidden module(s): {offenders}"


