def get_piv_matrix(results_list):
    full_dict = {seed: results_list[s_idx]['eq_series'] for s_idx, seed in enumerate(SEEDS)}
    df_eq = pd.DataFrame(full_dict)
    df_eq.index = pd.to_datetime(df_eq.index)
    median_eq = df_eq.median(axis=1)
    median_eq.index = pd.to_datetime(median_eq.index)

    try: m_eq = median_eq.resample('ME').last()
    except Exception: m_eq = median_eq.resample('M').last()

    m_eq = pd.concat([pd.Series([INITIAL_CAPITAL], index=[pd.to_datetime('2022-12-31')]), m_eq])
    m_rets = m_eq.pct_change().dropna() * 100.0

    m_df = pd.DataFrame({'Year': m_rets.index.year, 'Month': m_rets.index.month, 'Return': m_rets.values})
    month_cols = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
    piv = m_df.pivot(index='Year', columns='Month', values='Return')
    piv.columns = [month_cols[m-1] for m in piv.columns]

    for y in piv.index:
        y_sub = median_eq[median_eq.index.year == y]
        if len(y_sub) > 0:
            prev_years = median_eq[median_eq.index.year < y]
            start_val = prev_years.iloc[-1] if len(prev_years) > 0 else INITIAL_CAPITAL
            piv.loc[y, 'YTD Total'] = ((y_sub.iloc[-1] - start_val) / start_val) * 100.0
            cummax = y_sub.cummax()
            dd = (y_sub - cummax) / cummax * 100.0
            piv.loc[y, 'Max DD'] = dd.min()
    return piv

